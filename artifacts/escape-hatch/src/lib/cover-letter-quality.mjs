// Pure, non-mutating evaluation seam. No private text, inferred ratings, submission authority or semantic truth claims.
// See career-claim-fidelity.v1.json, career-artifact-propagation.v1.json and writing evaluation PR #131.
export function evaluateCoverLetter(input) {
  if (!input || typeof input !== "object" || typeof input.text !== "string" || !input.text.trim()) throw new TypeError("Nonempty letter required");
  const { text, employer, role, signature, approvedText } = input;
  if ([employer, role, signature].some(v => typeof v !== "string" || !v.trim())) throw new TypeError("Expected employer, role and signature required");
  const normalize = value => value.normalize("NFKC").toLowerCase().replace(/\s+/g, " ").trim();
  const contains = value => normalize(text).includes(normalize(value));
  const findings = [];
  const patterns = [
    ["PLACEHOLDER", /\{\{[^{}\n]+\}\}|\$\{[^{}\n]+\}|<<[^<>\n]+>>|\[(?:your|insert|company|employer|hiring manager|name|job title|position|date|address|signature|recipient|placeholder)\b[^\]\n]*\]/i],
    ["TEMPLATE_INSTRUCTION", /(?:^|\n)\s*(?:\(?insert (?:your|the|a)\b|replace (?:this|the placeholder|with)\b|customize (?:this|the)\b|here(?:'s| is) (?:your|a) (?:tailored |revised )?cover letter\b)/i],
    ["MARKUP", /(?:^|\n)\s*(?:```|#{1,6}\s)|\*\*[^*\n]+\*\*/],
    ["AI_META", /\b(?:as an AI (?:language model|assistant)|generated by ChatGPT)\b/i]
  ];
  for (const [code, pattern] of patterns) if (pattern.test(text)) findings.push(code);
  if (!contains(employer)) findings.push("EMPLOYER_MISSING");
  if (!contains(role)) findings.push("ROLE_MISSING");
  if (normalize(text.trim().split(/\r?\n/).filter(line=>line.trim()).at(-1)) !== normalize(signature)) findings.push("SIGNATURE_MISMATCH");
  if (approvedText !== undefined && typeof approvedText !== "string") throw new TypeError("Approved text must be a string");
  const approval = approvedText === undefined ? "UNSCORED" : approvedText === text ? "PASS" : "REJECT";
  const unscored = () => ({ state: "UNSCORED" });
  return {
    release: findings.length || approval === "REJECT" ? "REJECT" : "REVIEW_REQUIRED",
    findings,
    dimensions: {
      CL01: { state: contains(employer) && contains(role) ? "OBSERVED" : "REVIEW_REQUIRED", employerMentioned: contains(employer), roleMentioned: contains(role) },
      CL02: unscored(), CL03: unscored(), CL04: unscored(), CL05: unscored(),
      CL06: { state: findings.length ? "REJECT" : "PASS", scope: "known lexical hazards and expected identity only" },
      CL07: unscored(),
      CL08: { state: "OBSERVED", words: text.trim().split(/\s+/u).length, paragraphs: text.trim().split(/\r?\n\s*\r?\n/u).length },
      CL09: { state: approval },
      CL10: unscored()
    }
  };
}
