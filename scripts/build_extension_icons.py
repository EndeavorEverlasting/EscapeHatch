#!/usr/bin/env python3
"""Derive extension PNGs from the approved mascot, without changing its design.

Build dependency: python -m pip install Pillow==12.3.0
Regenerate: python scripts/build_extension_icons.py
Verify exact generated bytes: python scripts/build_extension_icons.py --check

BRAND_IDENTITY.md owns the source asset and digest. PNG encoding uses fixed
filter-zero RGBA rows and stored DEFLATE blocks, avoiding encoder metadata or
compression-version drift. Pillow is pinned for WebP decoding/LANCZOS resizing.
"""
from __future__ import annotations

import argparse
import hashlib
import struct
import sys
import zlib
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "artifacts/escape-hatch/public/escapehatch-mascot.webp"
OUTPUT = ROOT / "browser/application-assist/icons"
SOURCE_SHA256 = "e1e0f6e7ff0470231ae3ffa042e6a36555659a86ea070bee036e2badcec76451"
PILLOW_VERSION = "12.3.0"
PIPELINE = f"Pillow {PILLOW_VERSION}; RGBA LANCZOS; PNG filter=0 stored-deflate v1"
SIZES = (16, 32, 48, 128)


def chunk(kind: bytes, data: bytes) -> bytes:
    return struct.pack(">I", len(data)) + kind + data + struct.pack(">I", zlib.crc32(kind + data))


def png_rgba(size: int, pixels: bytes) -> bytes:
    stride = size * 4
    rows = b"".join(b"\0" + pixels[start:start + stride] for start in range(0, len(pixels), stride))
    blocks = []
    for start in range(0, len(rows), 65535):
        data = rows[start:start + 65535]
        final = start + len(data) == len(rows)
        blocks.append(bytes([int(final)]) + struct.pack("<HH", len(data), len(data) ^ 65535) + data)
    stream = b"\x78\x01" + b"".join(blocks) + struct.pack(">I", zlib.adler32(rows))
    return b"\x89PNG\r\n\x1a\n" + b"".join([
        chunk(b"IHDR", struct.pack(">IIBBBBB", size, size, 8, 6, 0, 0, 0)),
        chunk(b"tEXt", b"EscapeHatchSourceSHA256\0" + SOURCE_SHA256.encode("ascii")),
        chunk(b"tEXt", b"EscapeHatchGenerator\0" + PIPELINE.encode("ascii")),
        chunk(b"IDAT", stream), chunk(b"IEND", b""),
    ])


def render_icons() -> dict[int, bytes]:
    import PIL
    from PIL import Image

    if PIL.__version__ != PILLOW_VERSION:
        raise RuntimeError(f"Install Pillow=={PILLOW_VERSION} to reproduce the approved icon pipeline.")
    if hashlib.sha256(SOURCE.read_bytes()).hexdigest() != SOURCE_SHA256:
        raise RuntimeError("Canonical mascot changed; reconcile BRAND_IDENTITY.md before regenerating icons.")
    with Image.open(SOURCE) as source:
        if source.size != (128, 128):
            raise RuntimeError("Expected the approved 128px mascot; never enlarge a smaller derivative.")
        rgba = source.convert("RGBA")
        return {size: png_rgba(size, rgba.resize((size, size), Image.Resampling.LANCZOS).tobytes()) for size in SIZES}


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="Fail on missing/stale icons without writing.")
    args = parser.parse_args()
    try:
        icons = render_icons()
        for size, content in icons.items():
            destination = OUTPUT / f"mascot-{size}.png"
            if args.check:
                if not destination.is_file() or destination.read_bytes() != content:
                    raise RuntimeError(f"Stale icon: {destination.relative_to(ROOT)}; run this script without --check.")
            else:
                OUTPUT.mkdir(parents=True, exist_ok=True)
                destination.write_bytes(content)
        print("PASS approved mascot icons: " + ("exact regeneration verified" if args.check else "16, 32, 48 and 128px PNGs generated"))
        return 0
    except (ImportError, OSError, RuntimeError) as error:
        print(f"Extension icon build failed: {error}", file=sys.stderr)
        return 1


if __name__ == "__main__":
    raise SystemExit(main())
